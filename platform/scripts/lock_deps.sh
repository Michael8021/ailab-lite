#!/usr/bin/env bash
# Regenerate platform/constraints.txt: every runtime, dev and opensandbox dependency pinned to one version.
# Installs read it with `pip install -c constraints.txt ...` (Dockerfile, CI), so builds are reproducible.
#
#   bash scripts/lock_deps.sh            re-resolve to the newest versions allowed by pyproject.toml
#   bash scripts/lock_deps.sh --check    fail if constraints.txt no longer satisfies pyproject.toml (CI)
set -euo pipefail
cd "$(dirname "${BASH_SOURCE[0]}")/.."

tmp=$(mktemp -d); trap 'rm -rf "$tmp"' EXIT
python3 -m venv "$tmp/venv"
"$tmp/venv/bin/pip" install -q uv

compile() {  # output file
  "$tmp/venv/bin/uv" pip compile pyproject.toml --extra dev --extra opensandbox --extra postgres --python-version 3.12 \
    --no-header --quiet --output-file "$1" "${@:2}"
}

if [ "${1:-}" = "--check" ]; then
  # keep the pins we have; only complain if pyproject asks for something they cannot satisfy
  compile "$tmp/check.txt" --constraint constraints.txt
  diff <(grep -E '^[A-Za-z0-9_.\[\]-]+==' constraints.txt) <(grep -E '^[A-Za-z0-9_.\[\]-]+==' "$tmp/check.txt") >/dev/null \
    && echo "constraints.txt is consistent with pyproject.toml" \
    || { echo "constraints.txt is out of date: run  bash scripts/lock_deps.sh" >&2; exit 1; }
else
  compile "$tmp/resolved.txt"   # (its own statement, so a failure stops the script)
  grep -q '==' "$tmp/resolved.txt" || { echo "resolution produced no pins" >&2; exit 1; }
  {
    echo "# Generated by scripts/lock_deps.sh - do not edit. Update with: bash scripts/lock_deps.sh"
    echo "# Used as:  pip install -c constraints.txt -e '.[dev]'"
    cat "$tmp/resolved.txt"
  } > constraints.txt
  echo "wrote constraints.txt ($(grep -c '==' constraints.txt) pinned packages)"
fi
